function randomItem<T>(items: readonly T[]): T {
  return items[Math.floor(Math.random() * items.length)]!
}

export function createSoloGroupName(game: PoeGame): string {
  const prefix = randomItem(SHARED_PREFIXES)
  const suffix = randomItem(game === 'poe2' ? POE2_SUFFIXES : POE1_SUFFIXES)
  return `${prefix} ${suffix}`
}
