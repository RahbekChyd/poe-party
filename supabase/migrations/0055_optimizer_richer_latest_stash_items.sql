CREATE OR REPLACE VIEW public.latest_stash_items AS
SELECT
  si.id,
  si.tab_id,
  si.user_id,
  si.group_id,
  si.poe_item_id,
  si.name,
  si.base_type,
  si.type_line,
  si.item_class,
  si.frame_type,
  si.ilvl,
  si.icon_url,
  si.stack_size,
  si.identified,
  si.corrupted,
  si.fractured,
  si.synthesised,
  si.price_chaos,
  si.price_divine,
  si.mods,
  si.created_at,
  si.is_excluded,
  si.excluded_reason,
  st.name      AS tab_name,
  st.tab_type  AS tab_type,
  st.colour_r  AS colour_r,
  st.colour_g  AS colour_g,
  st.colour_b  AS colour_b,
  si.sockets,
  si.raw_data
FROM public.stash_items si
JOIN public.stash_tabs  st ON si.tab_id = st.id
WHERE st.snapshot_id IN (SELECT id FROM public.latest_snapshots);
